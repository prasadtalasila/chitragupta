"""The book's Glossary and List of Symbols, written as LaTeX from the
terminology registry (#1138): `registry build --glossary/--notation`.

Composition, not prose: every word comes from a unit's glossary or
`math.md` `## Symbols` (#1143); layout is in plans/tb-10-book-glossary.md.
A symbol naming different things gets a row per meaning, so the clash
shows on the page as well as in `registry check`. No timestamp, so
rebuilds over unchanged units are byte-identical.
"""

import os
import re
import tempfile
from pathlib import Path

from chitragupta.registry import _symbols
from chitragupta.registry._terms import term_key
from chitragupta.render_output._math import _GREEK_NAMES

_BANNER = (
    "% Generated by `python -m chitragupta.draft registry build {flag}`\n"
    "% from the accepted units' scope.md glossaries and math.md symbols.\n"
    "% Edit those, not this.\n"
)

_GREEK = re.compile(rf"^(?:{'|'.join(sorted(_GREEK_NAMES))})(?=$|[_^])")


def _grouped(rows, key) -> "dict[str, list[dict]]":
    grouped: dict[str, list[dict]] = {}
    for row in rows:
        grouped.setdefault(key(row), []).append(row)
    return grouped


def _in_order(built: dict, rows: "list[dict]") -> "list[dict]":
    """`rows` in outline order, then by their line in `scope.md` or
    `math.md`."""
    position = {unit_id: i for i, unit_id in enumerate(built["accepted"])}
    return sorted(rows, key=lambda row: (position[row["unit"]], row["line"]))


def _units(rows: "list[dict]") -> "list[str]":
    return list(dict.fromkeys(row["unit"] for row in rows))


def _with_symbols(text: str, symbols: "list[str]") -> str:
    return f"{text} ({', '.join(symbols)})" if symbols else text


def _linked(built: dict) -> "dict[tuple[str, str], list[str]]":
    """`(unit, term key)` -> the symbols that unit's `## Symbols` links to
    the term, as Markdown, in file order."""
    linked: dict[tuple[str, str], list[str]] = {}
    for row in _in_order(built, _symbols.resolved(built)):
        if row["kind"] == "link":
            found = linked.setdefault((row["unit"], term_key(row["text"])), [])
            if row["symbol_markdown"] not in found:
                found.append(row["symbol_markdown"])
    return linked


def glossary_entries(built: dict) -> "list[tuple[str, list[tuple[str, list[str]]]]]":
    """`(heading, [(definition, unit ids)])` per term, alphabetical, as
    Markdown."""
    linked = _linked(built)
    entries = []
    for key, rows in sorted(_grouped(_in_order(built, built["terms"]), _term_of).items()):
        definitions = []
        for text, same in _grouped(rows, lambda row: row["markdown"]).items():
            symbols = [s for row in same for s in linked.get((row["unit"], key), [])]
            definitions.append((text, _units(same), list(dict.fromkeys(symbols))))
        if len({tuple(symbols) for _, _, symbols in definitions}) == 1:
            heading = _with_symbols(rows[0]["term"], definitions[0][2])
            entries.append((heading, [(text, units) for text, units, _ in definitions]))
            continue
        numbered = [
            (f"({', '.join(symbols)}) {text}" if symbols else text, units)
            for text, units, symbols in definitions
        ]
        entries.append((rows[0]["term"], numbered))
    return entries


def _term_of(row: dict) -> str:
    return term_key(row["term"])


def _symbol_order(symbol: str) -> "tuple[int, str, str]":
    lower = symbol.lower()
    if _GREEK.match(lower):
        return (1, lower, symbol)
    return (0 if lower[:1].isalpha() else 2, lower, symbol)


def notation_rows(built: dict) -> "list[tuple[str, str, list[str]]]":
    rows = []
    for _, found in sorted(
        _grouped(_in_order(built, _symbols.resolved(built)), lambda row: row["symbol"]).items(),
        key=lambda item: _symbol_order(item[0]),
    ):
        # `registry check`'s `[notation]` meaning key, so page and check
        # agree on what one meaning is.
        for same in _grouped(found, lambda row: row["key"]).values():
            # Typeset as the defining unit does; a mismatch is a finding.
            source = next((row for row in same if row["kind"] != "see"), same[0])
            rows.append((source["symbol_markdown"], source["label"], _units(same)))
    return rows


def _cref(units: "list[str]") -> str:
    """One `\\Cref` per unit, in outline order: a grouped `\\Cref{a,b}`
    counts an appendix as a chapter ("Chapters A and 7", measured on the
    real book)."""
    return "(" + ", ".join(f"\\Cref{{{unit}}}" for unit in units) + ")"


def _opening(flag: str, title: str) -> "list[str]":
    """The page's unnumbered chapter, its contents line and its running
    head. `\\chapter*` sets no mark, so without `\\markboth` pages carried
    the last appendix's heads (#1182)."""
    return [
        _BANNER.format(flag=flag) + f"\\chapter*{{{title}}}",
        f"\\addcontentsline{{toc}}{{chapter}}{{{title}}}",
        f"\\markboth{{\\MakeUppercase{{{title}}}}}{{\\MakeUppercase{{{title}}}}}",
    ]


def _glossary_tex(entries, latex) -> str:
    lines = _opening("--glossary", "Glossary") + ["\\begin{description}"]
    for heading, definitions in entries:
        if len(definitions) == 1:
            ((text, units),) = definitions
            lines.append(f"\\item[{{{latex[heading]}}}] {latex[text]} {_cref(units)}")
            continue
        lines += [f"\\item[{{{latex[heading]}}}]", "  \\begin{enumerate}"]
        lines += [f"  \\item {latex[text]} {_cref(units)}" for text, units in definitions]
        lines.append("  \\end{enumerate}")
    return "\n".join(lines + ["\\end{description}"]) + "\n"


def _notation_tex(rows, latex) -> str:
    lines = _opening("--notation", "List of Symbols")
    lines.append("\\begin{longtable}{@{}l p{0.55\\textwidth} p{0.25\\textwidth}@{}}")
    for symbol, label, units in rows:
        lines.append(f"{latex[symbol]} & {latex[label]} & {_cref(units)[1:-1]} \\\\")
    return "\n".join(lines + ["\\end{longtable}"]) + "\n"


def render(built: dict, convert) -> "tuple[str | None, str | None]":
    """The two pages as LaTeX, or `None` for one with nothing on it.

    `convert` (`markdown_to_latex`) is passed in so the layout is
    testable without pandoc; it is called once for all text.
    """
    entries, rows = glossary_entries(built), notation_rows(built)
    texts = [heading for heading, _ in entries]
    texts += [text for _, definitions in entries for text, _ in definitions]
    texts += [text for symbol, label, _ in rows for text in (symbol, label)]
    unique = list(dict.fromkeys(texts))
    latex = dict(zip(unique, convert(unique)))
    return (
        _glossary_tex(entries, latex) if entries else None,
        _notation_tex(rows, latex) if rows else None,
    )


def write(path: Path, text: str) -> None:
    """`text` to `path` via a same-directory temp file, so a failure never
    leaves a half-written page."""
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(handle, "w", encoding="utf-8") as out:
            out.write(text)
        os.replace(temporary, path)
    except BaseException:
        os.unlink(temporary)
        raise
