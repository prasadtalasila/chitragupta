"""The book's Glossary and List of Symbols, written as LaTeX from the
terminology registry (#1138): `registry build --glossary/--notation`.

Composition, not prose: every word on both pages is a unit's own
`scope.md` glossary, and nothing here writes a definition. The layout
decisions, recorded in plans/tb-10-book-glossary.md:

- **Glossary.** One entry per term (`registry._terms.term_key`),
  alphabetical. A term with one definition prints it inline; with
  several, a numbered list in outline order. Each definition ends with
  the chapters it came from as `\\Cref{<unit-id>}`, which the
  assembler's `\\label{<unit-id>}` turns into "Chapter 3" (and, under
  the skeleton's cleveref, "Chapter A" for an appendix).
  Identical definitions print once with every chapter.
- **List of Symbols.** One table for the whole book. A symbol with one
  meaning across chapters is one row listing them; a symbol naming
  different things gets a row per meaning, so the clash is on the page
  as well as in `registry check`.

Deterministic: no timestamp, so rebuilding over unchanged units is
byte-identical, the rule the other registries follow.
"""

import os
import re
import tempfile
from pathlib import Path

from chitragupta.registry._terms import term_key
from chitragupta.render_output._math import _GREEK_NAMES

_BANNER = (
    "% Generated by `python -m chitragupta.draft registry build {flag}`\n"
    "% from the accepted units' scope.md glossaries. Edit those, not this.\n"
)

_GREEK = re.compile(rf"^(?:{'|'.join(sorted(_GREEK_NAMES))})(?=$|[_^])")


def _grouped(rows, key) -> "dict[str, list[dict]]":
    grouped: dict[str, list[dict]] = {}
    for row in rows:
        grouped.setdefault(key(row), []).append(row)
    return grouped


def _in_order(built: dict, rows: "list[dict]") -> "list[dict]":
    """`rows` in outline order, then by their line in `scope.md`."""
    position = {unit_id: i for i, unit_id in enumerate(built["accepted"])}
    return sorted(rows, key=lambda row: (position[row["unit"]], row["line"]))


def _units(rows: "list[dict]") -> "list[str]":
    return list(dict.fromkeys(row["unit"] for row in rows))


def _heading(row: dict) -> str:
    symbol = f" ({row['symbol_markdown']})" if row["symbol_markdown"] else ""
    return row["term"] + symbol


def glossary_entries(built: dict) -> "list[tuple[str, list[tuple[str, list[str]]]]]":
    """`(heading, [(definition, unit ids)])` per term, alphabetical, as
    Markdown."""
    named = _in_order(built, [row for row in built["terms"] if row["kind"] == "term"])
    entries = []
    for _, rows in sorted(_grouped(named, lambda row: term_key(row["term"])).items()):
        definitions = _grouped(rows, lambda row: row["markdown"])
        entries.append((_heading(rows[0]), [(d, _units(r)) for d, r in definitions.items()]))
    return entries


def _symbol_order(symbol: str) -> "tuple[int, str, str]":
    lower = symbol.lower()
    if _GREEK.match(lower):
        return (1, lower, symbol)
    return (0 if lower[:1].isalpha() else 2, lower, symbol)


def notation_rows(built: dict) -> "list[tuple[str, str, list[str]]]":
    """`(symbol, meaning, unit ids)` per symbol and meaning, as Markdown."""
    with_symbol = _in_order(built, [row for row in built["terms"] if row["symbol"]])
    rows = []
    for _, found in sorted(
        _grouped(with_symbol, lambda row: row["symbol"]).items(),
        key=lambda item: _symbol_order(item[0]),
    ):
        meanings = _grouped(
            found, lambda row: term_key(row["term"]) if row["kind"] == "term" else row["markdown"]
        )
        for same in meanings.values():
            first = same[0]
            meaning = first["term"] if first["kind"] == "term" else first["markdown"]
            rows.append((first["symbol_markdown"], meaning, _units(same)))
    return rows


def _cref(units: "list[str]") -> str:
    """One `\\Cref` per unit, in outline order. A grouped `\\Cref{a,b}`
    sorts by counter value and counts an appendix as a chapter, printing
    "Chapters A and 7" for chapter 7 and appendix A (measured on the real
    book's build)."""
    return "(" + ", ".join(f"\\Cref{{{unit}}}" for unit in units) + ")"


def _glossary_tex(entries, latex) -> str:
    lines = [_BANNER.format(flag="--glossary") + "\\chapter*{Glossary}"]
    lines += ["\\addcontentsline{toc}{chapter}{Glossary}", "\\begin{description}"]
    for heading, definitions in entries:
        if len(definitions) == 1:
            ((text, units),) = definitions
            lines.append(f"\\item[{{{latex[heading]}}}] {latex[text]} {_cref(units)}")
            continue
        lines += [f"\\item[{{{latex[heading]}}}]", "  \\begin{enumerate}"]
        lines += [f"  \\item {latex[text]} {_cref(units)}" for text, units in definitions]
        lines.append("  \\end{enumerate}")
    return "\n".join(lines + ["\\end{description}"]) + "\n"


def _notation_tex(rows, latex) -> str:
    lines = [_BANNER.format(flag="--notation") + "\\chapter*{List of Symbols}"]
    lines += [
        "\\addcontentsline{toc}{chapter}{List of Symbols}",
        "\\begin{longtable}{@{}l p{0.55\\textwidth} p{0.25\\textwidth}@{}}",
    ]
    for symbol, meaning, units in rows:
        lines.append(f"{latex[symbol]} & {latex[meaning]} & {_cref(units)[1:-1]} \\\\")
    return "\n".join(lines + ["\\end{longtable}"]) + "\n"


def render(built: dict, convert) -> "tuple[str | None, str | None]":
    """The two pages as LaTeX, or `None` for one with nothing on it.

    `convert` is `render_output._pandoc.markdown_to_latex`, passed in so
    the layout is testable without pandoc. Every Markdown text on both
    pages goes through it in one call.
    """
    entries, rows = glossary_entries(built), notation_rows(built)
    texts = [heading for heading, _ in entries]
    texts += [text for _, definitions in entries for text, _ in definitions]
    texts += [text for symbol, meaning, _ in rows for text in (symbol, meaning)]
    unique = list(dict.fromkeys(texts))
    latex = dict(zip(unique, convert(unique)))
    return (
        _glossary_tex(entries, latex) if entries else None,
        _notation_tex(rows, latex) if rows else None,
    )


def write(path: Path, text: str) -> None:
    """`text` to `path` through a temporary file in the same directory,
    so a failure never leaves a half-written page behind."""
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(handle, "w", encoding="utf-8") as out:
            out.write(text)
        os.replace(temporary, path)
    except BaseException:
        os.unlink(temporary)
        raise
