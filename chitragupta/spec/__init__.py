"""The outline a book is generated from, and the human sign-off on it.

`content/specs/<book>/spec.md` plus a `signoff.md` beside it.
**Planned top-down, generated bottom-up** (#136): the structure lives
on disk, so a document larger than a context window is tractable.
The sign-off is a separate file because writing the digest into
`spec.md` would change what it measured. Ids are mandatory, never
derived from headings, so a reworded heading cannot orphan written
units. `status`'s exit code records a person's decision and is not a
gate (docs/WRITE-A-BOOK.md). Stdlib only, so a genre skill can read a
slice with no venv.
"""

import hashlib
import re
from pathlib import Path

from chitragupta import config
from chitragupta.citekey_safety import citekey_problem

# Fence tracking reused from `_prose_lines` rather than a second copy: a
# `# comment` in a brief's fenced block would otherwise refuse the outline.
from chitragupta.dossier._sections import _prose_lines
from chitragupta.spec import _matter
from chitragupta.spec._matter import BACK, FRONT, GENERATED, matter

SPEC_MD = "spec.md"


SIGNOFF_MD = "signoff.md"

# Heading depth -> kind. Four levels: the section (level 4) is the
# generation unit (#137), so anything deeper would be generated by nothing.
_KINDS = {2: "part", 3: "chapter", 4: "section"}

# The id is optional in the *regex* and required by `_unit_problem`, so a
# heading missing its id is reported by name.
_HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*(?:\{#([^}\s]+)\})?\s*$")


class SpecError(Exception):
    """A book path outside `content/drafts/`, a book with no spec yet, or a
    chapter path that leaves its book."""


def spec_dir(book: Path) -> Path:
    """Where `book`'s spec lives: the book's whole relative path mirrored.

    Raises for a book outside `content/drafts/`, as `dossier.dossier_dir`
    does: an unmirrored artefact is found by nothing later.
    """
    try:
        relative = Path(book).resolve().relative_to(config.DRAFTS_DIR.resolve())
    except ValueError as exc:
        raise SpecError(
            f"{book} is not under {config.DRAFTS_DIR}. A spec mirrors its book's "
            "path, so the book has to live where the genre skills save a draft."
        ) from exc
    target = config.SPECS_DIR / relative
    # Both sides are resolved; this catches a content/specs/ directory
    # symlinked out of the tree, as `dossier.dossier_dir` does.
    if not config.resolves_inside(target, config.SPECS_DIR):
        raise SpecError(
            f"{target} resolves to {target.resolve()}, outside "
            f"{config.SPECS_DIR.resolve()}. Remove the symlink, or point "
            "[content].dir (config.toml) at the tree you are really working in."
        )
    return target


def spec_path(book: Path) -> Path:
    return spec_dir(book) / SPEC_MD


def signoff_path(book: Path) -> Path:
    return spec_dir(book) / SIGNOFF_MD


def digest(text: str) -> str:
    """A short fingerprint of a spec's text.

    Twelve hex characters like `dossier.digest`, but order-sensitive:
    the outline's order is exactly what must be covered.
    """
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


def chapter_digests(text: str) -> dict[str, str]:
    """A digest per chapter, over its `###` heading and everything below it.

    The whole-file digest froze acceptance book-wide when one brief was
    edited (#465). Keyed by id, so rewording cannot orphan an approval.
    Headings are found via `_prose_lines`, but spans are digested from
    **raw** lines, fences included (#506/M-27): a fenced example is part
    of what a person approves.
    """
    lines = text.splitlines()
    # (line index, chapter id or None) per part/chapter heading. `None`
    # closes a span without opening one (a part, or an id-less heading).
    boundaries: list[tuple[int, str | None]] = []
    for number, line in _prose_lines(lines):
        match = _HEADING.match(line)
        if match and len(match.group(1)) <= 3:
            chapter = match.group(3) if len(match.group(1)) == 3 else None
            boundaries.append((number - 1, chapter))

    digests: dict[str, str] = {}
    for position, (start, chapter) in enumerate(boundaries):
        if chapter is None:
            continue
        following = boundaries[position + 1 :]
        end = following[0][0] if following else len(lines)
        digests[chapter] = digest("\n".join(lines[start:end]))
    return digests


def _headings(text: str) -> list[dict]:
    """Every heading in `text`, each carrying the lines beneath it.

    Prose before the first heading is for the human; no unit comes of it.
    """
    found: list[dict] = []
    for _, line in _prose_lines(text.splitlines()):
        match = _HEADING.match(line)
        if match:
            found.append(
                {
                    "level": len(match.group(1)),
                    "title": match.group(2),
                    "id": match.group(3),
                    "brief": [],
                }
            )
        elif found:
            found[-1]["brief"].append(line)
    return found


def _unit_problem(head: dict, seen: set[str], stack: list[dict]) -> str | None:
    if head["level"] > 4:
        return (
            f"`{head['title']}` is deeper than a section. A section is the "
            "generation unit; there is nothing below it to generate."
        )
    if not head["id"]:
        return (
            f"`{head['title']}` has no `{{#id}}`. Every part, chapter and "
            "section needs one, so a reworded heading does not orphan the "
            "units written against it."
        )
    unsafe = citekey_problem(head["id"])
    if unsafe:
        return (
            f"`{head['title']}`'s id `{head['id']}` cannot be a filename: {unsafe}. "
            "An id is joined into a path under content/specs/, so the rule for "
            "one is the rule a citekey already obeys."
        )
    if head["id"] in seen:
        return (
            f"`{head['id']}` is used more than once. An id has to name one "
            "unit for a cross-reference to resolve."
        )
    above = stack[-1]["level"] if stack else 1
    if head["level"] > above + 1:
        kind = _KINDS[head["level"]]
        return (
            f"`{head['title']}` is a {kind} directly under a "
            f"{_KINDS.get(above, 'book')}: a {kind} needs a "
            f"{_KINDS[head['level'] - 1]} above it."
        )
    return None


def _unit(head: dict, ancestors: list[dict]) -> dict:
    return {
        "id": head["id"],
        "kind": _KINDS[head["level"]],
        "title": head["title"],
        "brief": "\n".join(head["brief"]).strip(),
        "ancestors": [entry["id"] for entry in ancestors],
        "ancestor_titles": [entry["title"] for entry in ancestors],
    }


def _missing(title: str | None, units: list[dict]) -> list[str]:
    problems = []
    if title is None:
        problems.append("no book title: the spec's first heading should be `# <title>`.")
    if not units:
        problems.append(
            "no units: an outline with no part, chapter or section names nothing to generate."
        )
    return problems


def parse(text: str) -> dict:
    """`{"title", "author", "units", "problems"}` for a spec's text.

    Problems are collected, not raised one at a time, and a problem
    heading contributes no unit, so returned units are well-formed.
    """
    title = None
    author = None
    units: list[dict] = []
    problems: list[str] = []
    seen: set[str] = set()
    stack: list[dict] = []
    for head in _headings(text):
        if head["level"] == 1:
            if title is None:
                title = head["title"]
                author = _matter.author(head["brief"])
            else:
                problems.append(
                    f"more than one book title: `{head['title']}` is a "
                    "second `#` heading. A spec describes one book."
                )
            continue
        problem = _unit_problem(head, seen, stack)
        if problem:
            problems.append(problem)
            continue
        stack[:] = [entry for entry in stack if entry["level"] < head["level"]]
        units.append(_unit(head, stack))
        stack.append(head)
        seen.add(head["id"])
    problems += _matter.problems(units)
    return {
        "title": title,
        "author": author,
        "units": units,
        "problems": problems + _missing(title, units),
    }


